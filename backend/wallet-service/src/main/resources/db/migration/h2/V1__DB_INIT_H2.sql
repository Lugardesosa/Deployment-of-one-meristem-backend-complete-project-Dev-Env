CREATE TABLE wallets
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_date       TIMESTAMP                               NOT NULL,
    created_by         VARCHAR(255)                            NOT NULL,
    last_modified_date TIMESTAMP,
    last_modified_by   VARCHAR(255)                            NOT NULL,
    version            INTEGER,
    status             INTEGER        DEFAULT 1                NOT NULL,
    full_name          VARCHAR(200)                            NOT NULL,
    user_id            BIGINT                                  NOT NULL,
    balance            DECIMAL(14, 4) DEFAULT 0.0              NOT NULL,
    CONSTRAINT pk_wallets PRIMARY KEY (id)
);


CREATE TABLE virtual_accounts
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_date       TIMESTAMP                               NOT NULL,
    created_by         VARCHAR(255)                            NOT NULL,
    last_modified_date TIMESTAMP,
    last_modified_by   VARCHAR(255)                            NOT NULL,
    version            INTEGER,
    status             INTEGER DEFAULT 1                       NOT NULL,
    reference          VARCHAR(25)                             NOT NULL,
    bank_code          VARCHAR(20)                             NOT NULL,
    bank_name          VARCHAR(70)                             NOT NULL,
    account_number     VARCHAR(20)                             NOT NULL,
    account_name       VARCHAR(200)                            NOT NULL,
    provider_wallet_id VARCHAR(200)                            NOT NULL,
    balance            DECIMAL(14, 4)                          NOT NULL,
    wallet_id          BIGINT                                  NOT NULL,
    CONSTRAINT "pk_virtual_accounts" PRIMARY KEY (id)
);


CREATE TABLE transactions
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_date           TIMESTAMP                               NOT NULL,
    created_by             VARCHAR(255)                            NOT NULL,
    last_modified_date     TIMESTAMP,
    last_modified_by       VARCHAR(255)                            NOT NULL,
    version                INTEGER,
    status                 INTEGER DEFAULT 1                       NOT NULL,
    wallet_id              BIGINT                                  NOT NULL,
    virtual_account_id     BIGINT,
    reference              VARCHAR(50)                             NOT NULL,
    amount                 DECIMAL(14, 4)                          NOT NULL,
    previous_balance       DECIMAL(14, 4),
    new_balance            DECIMAL(14, 4),
    type                   INTEGER                                 NOT NULL,
    method                 INTEGER                                 NOT NULL,
    narration              VARCHAR(255),
    provider_reference     VARCHAR(50)                             NOT NULL,
    senders_bank_name      VARCHAR(100),
    senders_name           VARCHAR(100),
    senders_bank_code      VARCHAR(20),
    senders_account_number VARCHAR(20),
    transaction_date       TIMESTAMP                               NOT NULL,

    CONSTRAINT "pk_transactions" PRIMARY KEY (id)
);


